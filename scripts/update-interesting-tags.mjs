const root = path.resolve(import.meta.dirname, "..");
const catalog = JSON.parse(await readFile(path.join(root, "data", "tags.json"), "utf8"));
const previous = JSON.parse(await readFile(path.join(root, "data", "interesting-tags.json"), "utf8"));
const byName = new Map();
for (const tag of catalog.tags) {
  const key = tag.name.toLowerCase();
  const list = byName.get(key) ?? [];
  list.push(tag);
  byName.set(key, list);
}

const previousByName = new Map(previous.map((tag) => [tag.name.toLowerCase(), tag]));
const resolved = [];
const missing = [];
const ambiguous = [];

for (const name of names) {
  const matches = byName.get(name.toLowerCase()) ?? [];
  if (matches.length === 0) {
    missing.push(name);
    continue;
  }
  const prior = previousByName.get(name.toLowerCase());
  let chosen = matches.find((tag) => prior && tag.slug === prior.slug && tag.namespace === prior.namespace);
  if (!chosen) chosen = matches.find((tag) => tag.namespace === "artwork") ?? matches[0];
  if (matches.length > 1) {
    ambiguous.push({
      name,
      chosen: `${chosen.namespace}/${chosen.slug}`,
      options: matches.map((tag) => `${tag.namespace}/${tag.slug}`),
    });
  }
  resolved.push({ name: chosen.name, slug: chosen.slug, namespace: chosen.namespace });
}

const previousSlugs = new Set(previous.map((tag) => `${tag.namespace}:${tag.slug}`));
const added = resolved.filter((tag) => !previousSlugs.has(`${tag.namespace}:${tag.slug}`));
await writeFile(path.join(root, "data", "interesting-tags.json"), JSON.stringify(resolved, null, 2));
console.log(JSON.stringify({
  saved: resolved.length,
  artwork: resolved.filter((tag) => tag.namespace === "artwork").length,
  card: resolved.filter((tag) => tag.namespace === "card").length,
  added: added.map((tag) => `${tag.namespace}/${tag.slug}`),
  missing,
  ambiguous,
}, null, 2));
